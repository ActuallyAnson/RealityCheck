#!/bin/sh
# Builds docs/RESULTS.md from the tables the evaluation tools wrote (no hand-typed numbers).
set -e
cd "$(dirname "$0")/.."
out=docs/RESULTS.md
sec() { # title, file, note
  [ -f "$2" ] || return 0
  printf '\n## %s\n\n%s\n\nSource: `%s`\n\n' "$1" "$3" "$2" >> "$out"
  grep -v '^<!--' "$2" >> "$out"
}
printf '# Results (generated by scripts/gen_results.sh; do not edit)\n' > "$out"
sec "Ablation on fresh held-out bugs b11-b13 (rigid bodies, 10 seeds)" results/ablation/compare.md \
  "Arms: v1 (frozen original agent), v2 (counterfactual-checked reports, frames shown in the loop), v2 without frames, and the random baseline. Lock: data/eval_lock_ablation.json."
sec "Agent v1 on the rigid-body simulator v1 (5 seeds)" results/agent_hosted/summary.md "First evaluation; the simulator was later fixed (v2) after the controls found a weakness."
sec "Random baseline, rigid bodies, simulator v1" results/baseline.md ""
sec "Random baseline, rigid bodies, simulator v2 (b11-b13 added)" results/v2/baseline.md ""
sec "Orbit domain: agent v1" results/orbit_agent/summary.md "Bugs o01-o03, fresh when run. Random baseline below."
sec "Orbit domain: random baseline" results/orbit/baseline.md ""
sec "Cart-pole domain (envelope 3): agent v1" results/cartpole_agent/summary.md "Bugs c01-c03 had been seen in earlier attempts; see docs/CARTPOLE_DOMAIN.md for the history."
sec "Cart-pole domain (envelope 3): random baseline" results/cartpole/baseline.md ""
sec "Traffic-signal domain: agent v1" results/traffic_agent/summary.md "Bugs t01-t03, all fresh. Random testing finds all three in every seed; see docs/TRAFFIC_DOMAIN.md."
sec "Traffic-signal domain: random baseline" results/traffic/baseline.md ""
sec "Spec to rules: model-written invariants vs hand-written rules" results/spec_summary.md "One run per domain, 300 scenarios per bug; see docs/SPEC_RULES.md."
echo "wrote $out"
